-- Названия РЦ без номера (решение владельца 26.10.2026).
--
-- Номер живёт в колонке «Код», и в названии он лишний: на проде названия были вычищены руками,
-- а сид создавал новые стенды с префиксом («01.Реактор»). Из-за этого стенды расходились.
--
-- Скрипт идемпотентен: срезает числовой префикс только там, где он ещё есть («01.Реактор» →
-- «Реактор», «13.Ручн налив» → «Ручн налив»). На проде, где названия уже чистые, ничего не меняет.

UPDATE "work_centers"
SET "name" = regexp_replace("name", '^[0-9]+\.\s*', '')
WHERE "name" ~ '^[0-9]+\.\s*';
