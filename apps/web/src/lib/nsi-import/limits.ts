/**
 * Предел размера файла номенклатуры (правка под сервер 1 ГБ, 03.11.2026).
 *
 * Почему именно 3 МБ. Книга .xlsx разбирается целиком в памяти (ExcelJS), и пик памяти
 * на разбор — это несколько размеров файла: 10 МБ давали сотни мегабайт и могли убить
 * web-контейнер с лимитом 560 МБ и кучей 384 МБ. 3 МБ — это тысячи строк номенклатуры,
 * то есть с запасом хватает для штатной загрузки справочника, и при этом разбор остаётся
 * в безопасных пределах.
 *
 * Число живёт в одном месте: клиент проверяет его до отправки (чтобы человек увидел
 * понятное сообщение вместо ошибки 413), сервер ограничивает тело запроса в next.config.js
 * (`bodySizeLimit: '3mb'`). Эти два значения обязаны совпадать — при изменении править оба.
 */
export const IMPORT_MAX_FILE_BYTES = 3 * 1024 * 1024;

/** Человеческая подпись предела — для сообщений на экране. */
export const IMPORT_MAX_FILE_LABEL = '3 МБ';
