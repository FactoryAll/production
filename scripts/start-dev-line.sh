#!/usr/bin/env bash
# Готовит линию разработки и печатает инициирующий промпт для нового чата.
#
# Зачем: чтобы новая линия начиналась одинаково и не собирала контекст по крупицам.
# Скрипт проверяет второе рабочее дерево, синхронизирует его с main и печатает готовый
# текст, который вставляют в новый чат как первое сообщение.
#
# Использование (из каталога поддержки):
#   bash scripts/start-dev-line.sh            # подготовить и напечатать промпт
#   bash scripts/start-dev-line.sh --check    # только проверить состояние, без промпта
set -euo pipefail

# Корень репозитория берём у git, а не от места запуска: скрипт вызывают и из дерева
# поддержки, и из дерева разработки, и относительный путь от $0 давал
# `.worktrees/dev/.worktrees/dev` (дефект найден рабочей линией 28.10.2026).
ROOT="$(git -C "$(dirname "$0")/.." worktree list --porcelain | sed -n '1s/^worktree //p')"
if [ -z "${ROOT}" ] || [ ! -d "${ROOT}" ]; then
  echo "Не удалось определить корень репозитория (git worktree list)." >&2
  exit 1
fi
WORKTREE="${ROOT}/.worktrees/dev"
CHECK_ONLY=0
[ "${1:-}" = "--check" ] && CHECK_ONLY=1

cd "${ROOT}"

# 1. Второе дерево должно существовать и стоять на dev.
#
# Проверку делаем по строке, а не через `grep -q` в конвейере: под `pipefail` SIGPIPE
# от grep -q роняет весь конвейер, и существующее дерево объявляется отсутствующим
# (второй дефект этого скрипта, найден 28.10.2026).
WORKTREE_LIST="$(git worktree list --porcelain)"
case "${WORKTREE_LIST}" in
  *"worktree ${WORKTREE}"*) ;;
  *)
    echo "Второго дерева нет — создаю." >&2
    git worktree add "${WORKTREE}" dev
    ;;
esac

cd "${WORKTREE}"
CURRENT_BRANCH="$(git branch --show-current)"
if [ "${CURRENT_BRANCH}" != "dev" ]; then
  echo "ОШИБКА: дерево разработки на ветке ${CURRENT_BRANCH}, а должно быть на dev." >&2
  exit 1
fi

if [ -n "$(git status --porcelain)" ]; then
  echo "ВНИМАНИЕ: в дереве разработки есть незакоммиченные изменения — сначала разберитесь с ними." >&2
  git status --short | head -5 >&2
  exit 1
fi

# 2. Синхронизация с main: дев не должен отставать (правило №3).
git pull --quiet origin dev
git merge --no-edit main >/dev/null 2>&1 || git merge --no-edit main
git push --quiet origin dev 2>/dev/null || true

if [ "${CHECK_ONLY}" = "1" ]; then
  echo "Линия разработки готова: ${WORKTREE} (ветка dev)"
  exit 0
fi

# 3. Печатаем инициирующий промпт: его вставляют в новый чат.
HEAD_SHORT="$(git rev-parse --short HEAD)"
NEXT_TASK="$(grep -n '^### T-' tasks.md | tail -1 | sed 's/^[0-9]*:### //')"

cat <<PROMPT
Ты — линия разработки ProdTrack. Работай в этом каталоге:

    ${WORKTREE}

Ветка: dev (${HEAD_SHORT}). Правила обязательны, читай их целиком перед первой правкой:
docs/branching_model.md — разделы 1–11, особенно правило 11 «Два дерева, две линии».

Что тебе можно:
- работать только в ветке dev и только в этом каталоге;
- писать постановки (docs/), бэклог (tasks.md), спецификации (specs/), код и тесты;
- просить владельца собрать дев-стенд: docker compose -f docker-compose.dev.yml build && up -d,
  затем bash scripts/postdeploy-check.sh --dev.

Что нельзя (это работа линии поддержки):
- трогать ветки fix/* и main, сливать в main, выкладывать на прод;
- править docs/pilot_operation_journal.md — журнал находок ОПЭ ведёт поддержка;
- менять scripts/, docker-compose*.yml, .env* без согласования с поддержкой.

Очередь работ (P2, по решению владельца):
1. Табель учёта рабочего времени — постановка готова: docs/timesheet_design.md,
   задача T-093. Сначала закрыть её открытые вопросы (§10) с владельцем, потом проектировать.
2. Канбан производственного контура — задача T-103.
3. Отчёты из бэклога — T-097…T-101.

Правила работы, которые не обсуждаются:
- каждая правка сопровождается тестом, который падает без неё;
- перед коммитом: pnpm typecheck && pnpm lint && pnpm test && pnpm build
  (при ошибке депс-проверки pnpm: PNPM_CONFIG_VERIFY_DEPS_BEFORE_RUN=false);
- миграции создаются только в main — если нужна миграция, скажи владельцу, её сделает поддержка;
- «сделано» значит «собрано на проде»: на деве — это «проверено на деве, на прод не вынесено».

Связь с поддержкой: короткие сообщения через линию (line_notify по заголовку линии поддержки),
формат: что сделано → где смотреть (путь или коммит) → что делать дальше. Без секретов и тел отчётов.
PROMPT
